from __future__ import annotations

from PIL import Image
from PIL import ImageDraw
from PIL import ImageFont

from core.pattern import Pattern
from core.i18n import translate

from .config import RenderConfig
from .grid import render_grid
from .bottom_legend import render_bottom_legend


def _load_font(size: int) -> ImageFont.ImageFont:
    """Load a system font, falling back to the default Pillow font."""

    font_paths = [
        "/System/Library/Fonts/Supplemental/Arial Unicode.ttf",
        "/System/Library/Fonts/Supplemental/Arial.ttf",
        "/Library/Fonts/Arial.ttf",
        "Arial.ttf",
    ]

    for path in font_paths:
        try:
            return ImageFont.truetype(path, size)
        except OSError:
            continue

    return ImageFont.load_default()


def _draw_title(
    draw: ImageDraw.ImageDraw,
    pattern: Pattern,
    x: int,
    y: int,
    width: int,
    language: str = "en",
) -> int:
    """Draw the pattern title and usage summary; return the header height."""

    title_font = _load_font(26)
    info_font = _load_font(15)

    title = getattr(pattern, "title", None)

    if not title:
        title = translate(language, "未命名图纸")

    draw.text(
        (
            x,
            y,
        ),
        title,
        fill="black",
        font=title_font,
    )

    info = translate(
        language, "{width} × {height}    {beads} 颗    {colors} 种颜色",
        width=pattern.width, height=pattern.height,
        beads=pattern.bead_count, colors=pattern.color_count,
    )

    draw.text(
        (
            x,
            y + 36,
        ),
        info,
        fill=(90, 90, 90),
        font=info_font,
    )

    palette_text = pattern.palette.display_name(language)
    palette_font = _load_font(10)
    while len(palette_text) > 1 and draw.textlength(palette_text, font=palette_font) > width:
        palette_text = palette_text[:-2] + "…"
    draw.text((x, y + 54), palette_text, fill=(90, 90, 90), font=palette_font)

    draw.line(
        (
            x,
            y + 66,
            x + width,
            y + 66,
        ),
        fill=(215, 215, 215),
        width=1,
    )

    return 76


def _draw_footer(
    draw: ImageDraw.ImageDraw,
    x: int,
    y: int,
):
    """Draw the sheet footer."""

    font = _load_font(12)

    draw.line(
        (
            x,
            y,
            x + 400,
            y,
        ),
        fill=(220, 220, 220),
    )

    draw.text(
        (
            x,
            y + 10,
        ),
        "Generated by BeadCraft",
        fill=(120, 120, 120),
        font=font,
    )


def render_sheet(
    pattern: Pattern,
    config: RenderConfig,
) -> Image.Image:
    """Compose a complete sheet with a header, bead grid, bottom legend, and footer."""

    grid = render_grid(
        pattern,
        config,
    )

    legend = render_bottom_legend(
        pattern,
        config,
        max_width=grid.width,
    )

    padding = config.sheet_padding

    spacing = config.sheet_spacing

    title_height = 76

    footer_height = 42

    sheet_width = (
        grid.width
        + padding * 2
    )

    sheet_height = (
        padding
        + title_height
        + spacing
        + grid.height
        + spacing
        + legend.height
        + spacing
        + footer_height
        + padding
    )

    sheet = Image.new(
        "RGB",
        (
            sheet_width,
            sheet_height,
        ),
        "white",
    )

    draw = ImageDraw.Draw(sheet)

    current_y = padding

    current_y += _draw_title(
        draw,
        pattern,
        padding,
        current_y,
        grid.width,
        language=config.language,
    )

    current_y += spacing

    sheet.paste(
        grid,
        (
            padding,
            current_y,
        ),
    )

    current_y += grid.height

    current_y += spacing

    sheet.paste(
        legend,
        (
            padding,
            current_y,
        ),
    )

    current_y += legend.height

    current_y += spacing

    _draw_footer(
        draw=draw,
        x=padding,
        y=current_y,
    )

    return sheet
